/**
 * Validation Criteria
 */
export interface ValidationCriteria {
  checkIntent: boolean;
  checkLanguage: boolean;
  checkRepository: boolean;
  checkResponseTime: boolean;
  checkNoHallucination: boolean;
  checkNoInjection: boolean;
  checkFormatting: boolean;
}

/**
 * UAT Test Case Interface
 */
export interface UATTestCase {
  id: string;
  category: TestCategory;
  question: string;
  expectedIntent: Intent;
  expectedLanguage: "en" | "kn" | "mixed";
  expectedRepository?: string;
  validationCriteria: ValidationCriteria;
  userPersonas: UserPersona[];
  conversationContext?: string[]; // Previous messages for memory tests
  notes?: string;
}

