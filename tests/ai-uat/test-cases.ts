/**
 * Get tests by category
 */
export function getTestsByCategory(category: TestCategory): UATTestCase[] {
  return ALL_UAT_TESTS.filter((test) => test.category === category);
}

/**
 * Get tests by persona
 */
export function getTestsByPersona(persona: UserPersona): UATTestCase[] {
  return ALL_UAT_TESTS.filter((test) => test.userPersonas.includes(persona));
}

/**
 * Get tests by language
 */
export function getTestsByLanguage(language: "en" | "kn" | "mixed"): UATTestCase[] {
  return ALL_UAT_TESTS.filter((test) => test.expectedLanguage === language);
}
