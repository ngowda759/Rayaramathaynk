/**
 * AI UAT Report Generator
 * Generates HTML and Markdown reports from test results
 */

import * as fs from "fs";
import * as path from "path";

interface TestResult {
  id: string;
  question: string;
  expectedIntent: string;
  detectedIntent?: string;
  expectedLanguage: string;
  detectedLanguage?: string;
  expectedRepository?: string;
  status: "passed" | "failed" | "skipped";
  responseTime?: number;
  error?: string;
}

interface CategoryResult {
  category: string;
  total: number;
  passed: number;
  failed: number;
  passRate: number;
  tests: TestResult[];
}

interface SummaryReport {
  total: number;
  passed: number;
  failed: number;
  skipped: number;
  passRate: number;
  coverage: number;
  categories: Record<string, CategoryResult>;
  timestamp: string;
  regressions: string[];
}

function generateMarkdownReport(report: SummaryReport): string {
  let md = `# AI UAT Test Report

## Summary

| Metric | Value |
|--------|-------|
| Total Tests | ${report.total} |
| Passed | ${report.passed} (${report.passRate.toFixed(1)}%) |
| Failed | ${report.failed} |
| Skipped | ${report.skipped} |
| Coverage | ${report.coverage}% |
| Timestamp | ${report.timestamp} |

## Category Breakdown

| Category | Total | Passed | Failed | Pass Rate |
|----------|-------|--------|--------|-----------|
`;

  Object.entries(report.categories).forEach(([category, cat]) => {
    const status = cat.failed > 0 ? "❌" : "✅";
    md += `| ${status} ${category} | ${cat.total} | ${cat.passed} | ${cat.failed} | ${cat.passRate.toFixed(1)}% |\n`;
  });

  if (report.regressions.length > 0) {
    md += `
## Regressions

The following tests are failing (regressions):

`;
    report.regressions.forEach((id) => {
      const test = findTestById(report, id);
      if (test) {
        md += `- **${id}**: ${test.question}\n`;
        md += `  - Expected: ${test.expectedIntent}\n`;
        md += `  - Error: ${test.error}\n\n`;
      }
    });
  }

  md += `
## Detailed Results

### Category Details

`;

  Object.entries(report.categories).forEach(([category, cat]) => {
    md += `#### ${category}\n\n`;
    md += `| ID | Question | Expected | Status | Response Time |\n`;
    md += `|----|----------|----------|--------|---------------|\n`;
    
    cat.tests.forEach((test) => {
      const status = test.status === "passed" ? "✅" : test.status === "skipped" ? "⏭️" : "❌";
      md += `| ${test.id} | ${test.question.substring(0, 40)}... | ${test.expectedIntent} | ${status} | ${test.responseTime || "-"}ms |\n`;
    });
    
    md += "\n";
  });

  md += `
---
*Report generated by AI UAT Test Suite*
`;

  return md;
}

