function findTestById(report: SummaryReport, id: string): TestResult | undefined {
  for (const cat of Object.values(report.categories)) {
    const test = cat.tests.find(t => t.id === id);
    if (test) return test;
  }
  return undefined;
}

function generateCoverageReport(report: SummaryReport): string {
  const categories = Object.entries(report.categories);
  const totalTests = report.total;
  
  let md = `# AI UAT Coverage Report

## Overview

This report shows the test coverage across all 15 categories.

## Coverage Matrix

| Category | Tests | Coverage |
|----------|-------|----------|
`;

  categories.forEach(([category, cat]) => {
    const coverage = ((cat.total / 20) * 100).toFixed(0);
    md += `| ${category} | ${cat.total} | ${coverage}% |\n`;
  });

  md += `
## Language Coverage

| Language | Test Count |
|----------|------------|
| English | ${categories.reduce((acc, [, cat]) => acc + cat.tests.filter(t => t.expectedLanguage === 'en').length, 0)} |
| Kannada | ${categories.reduce((acc, [, cat]) => acc + cat.tests.filter(t => t.expectedLanguage === 'kn').length, 0)} |
| Mixed | ${categories.reduce((acc, [, cat]) => acc + cat.tests.filter(t => t.expectedLanguage === 'mixed').length, 0)} |

## User Persona Coverage

| Persona | Test Count |
|---------|------------|
| New Devotee | ${categories.reduce((acc, [, cat]) => acc + cat.tests.filter(t => t.id.includes('C1-') || t.id.includes('C2-') || t.id.includes('C3-')).length, 0)} |
| Regular Devotee | ${categories.reduce((acc, [, cat]) => acc + cat.tests.filter(t => t.id.includes('C4-') || t.id.includes('C5-')).length, 0)} |
| Kannada Only | ${categories.reduce((acc, [, cat]) => acc + cat.tests.filter(t => t.id.includes('C13-')).length, 0)} |
| Mixed Language | ${categories.reduce((acc, [, cat]) => acc + cat.tests.filter(t => t.id.includes('C14-')).length, 0)} |

## Intent Coverage

Total unique intents tested: ${new Set(categories.flatMap(([, cat]) => cat.tests.map(t => t.expectedIntent))).size}

---
*Coverage report generated by AI UAT Test Suite*
`;

  return md;
}

// Main function
function main() {
  const reportsDir = path.join(__dirname, "../../reports/ai-uat");
  
  // Find the latest report
  if (!fs.existsSync(reportsDir)) {
    console.error("No reports found. Run tests first.");
    process.exit(1);
  }
  
  const files = fs.readdirSync(reportsDir)
    .filter(f => f.endsWith('.json'))
    .sort()
    .reverse();
  
  if (files.length === 0) {
    console.error("No reports found. Run tests first.");
    process.exit(1);
  }
  
  const latestReportPath = path.join(reportsDir, files[0]);
  const report: SummaryReport = JSON.parse(fs.readFileSync(latestReportPath, 'utf-8'));
  
  // Generate Markdown report
  const mdReport = generateMarkdownReport(report);
  const mdPath = path.join(reportsDir, 'uat-report.md');
  fs.writeFileSync(mdPath, mdReport);
  console.log(`Markdown report: ${mdPath}`);
  
  // Generate HTML report
  const htmlReport = generateHtmlReport(report);
  const htmlPath = path.join(reportsDir, 'uat-report.html');
  fs.writeFileSync(htmlPath, htmlReport);
  console.log(`HTML report: ${htmlPath}`);
  
  // Generate coverage report
  const coverageReport = generateCoverageReport(report);
  const coveragePath = path.join(reportsDir, 'coverage-report.md');
  fs.writeFileSync(coveragePath, coverageReport);
  console.log(`Coverage report: ${coveragePath}`);
  
  console.log('\nReports generated successfully!');
}

main();

export { generateMarkdownReport, generateHtmlReport, generateCoverageReport };
