/**
 * Unit tests for the Aaradhane Supabase writer.
 *
 * The writer is the sole persistence path for generated Aaradhane events, so these
 * tests pin the properties that make that safe: the identity key, the ownership
 * refusal, plan-only runs never touching the client, and idempotent upsert.
 */

import type { SupabaseClient } from "@supabase/supabase-js";

import {
  AARADHANE_CATEGORY,
  AARADHANE_LOCATION,
  assertOwned,
  buildSupabaseEventRow,
  canonicalEventId,
  determineEventStatus,
  planWrite,
  unmappedFields,
  writeAaradhaneEvents,
} from "@/lib/aaradhane/supabase-writer";
import { GeneratedAaradhaneEvent } from "@/types/aaradhane-generator";

function event(overrides: Partial<GeneratedAaradhaneEvent> = {}): GeneratedAaradhaneEvent {
  return {
    eventKey: "raghavendra-2027",
    title: "Sri Raghavendra Swamy Aaradhane",
    description: "Aaradhane of Sri Raghavendra Swamy",
    date: "2027-08-15",
    endDate: "2027-08-17",
    year: 2027,
    category: "Aaradhane",
    guru: "raghavendra",
    guruName: "Sri Raghavendra Swamy",
    featured: true,
    published: false,
    autoGenerated: true,
    paramparaNumber: 1,
    raghavendraPhase: "first",
    lunarCalendar: { lunarMonth: "Shravana", paksha: "Shukla", tithi: "Trayodashi" },
    rituals: ["pada-puja"],
    offerings: ["panchamruta"],
    importance: "major",
    allDay: true,
    ...overrides,
  } as GeneratedAaradhaneEvent;
}

/**
 * Minimal stand-in for the Supabase client, recording the calls the writer makes.
 * Only the surface the writer actually uses is implemented.
 */
function stubClient(options: {
  existing?: Array<{ firestore_id: string; category: string | null }>;
  upsertError?: { message: string };
  perRowError?: (row: { firestore_id: string }) => { message: string } | null;
} = {}) {
  const calls: Array<{ op: string; rows?: unknown[]; conflict?: string; keys?: string[] }> = [];
  let upsertCount = 0;

  const client = {
    from() {
      return {
        select() {
          return {
            in(_column: string, keys: string[]) {
              calls.push({ op: "select", keys });
              return Promise.resolve({ data: options.existing ?? [], error: null });
            },
          };
        },
        upsert(rows: Array<{ firestore_id: string }>, opts?: { onConflict?: string }) {
          calls.push({ op: "upsert", rows, conflict: opts?.onConflict });
          upsertCount++;
          if (options.upsertError && upsertCount <= 3) {
            return Promise.resolve({ error: options.upsertError });
          }
          const err = options.perRowError?.(rows[0]);
          if (err && rows.length === 1) return Promise.resolve({ error: err });
          return Promise.resolve({ error: null });
        },
      };
    },
  } as unknown as SupabaseClient;

  return { client, calls };
}

describe("Aaradhane Supabase writer", () => {
  describe("canonical identity", () => {
    it("uses the generator's eventKey unchanged, with no invented prefix or phase suffix", () => {
      // Regression: an earlier plan proposed `generated-<year>-<guru>[-<phase>]`.
      // The generator has always emitted `${guru.id}-${year}`.
      expect(canonicalEventId(event())).toBe("raghavendra-2027");
      expect(canonicalEventId(event({ eventKey: "madhvacharya-2027" }))).toBe("madhvacharya-2027");
      expect(canonicalEventId(event())).not.toMatch(/^generated-/);
    });

    it("throws rather than inventing a key for an event without one", () => {
      expect(() => canonicalEventId(event({ eventKey: "" }))).toThrow(/no eventKey/);
    });
  });

  describe("determineEventStatus", () => {
    const now = new Date("2027-08-16T10:00:00Z");

    it("classifies past, present and future dates", () => {
      expect(determineEventStatus("2027-08-01", "2027-08-02", now)).toBe("Completed");
      expect(determineEventStatus("2027-08-15", "2027-08-17", now)).toBe("Ongoing");
      expect(determineEventStatus("2027-09-01", "2027-09-02", now)).toBe("Upcoming");
    });

    it("treats the end date as inclusive to the end of that day", () => {
      expect(determineEventStatus("2027-08-01", "2027-08-16", now)).toBe("Ongoing");
    });

    it("rejects unparseable dates instead of guessing", () => {
      expect(() => determineEventStatus("not-a-date", "2027-08-16", now)).toThrow(/Invalid event dates/);
    });
  });

  describe("row mapping", () => {
    it("maps every generated field either to a column or to the reported unmapped set", () => {
      const row = buildSupabaseEventRow(event());
      expect(row.firestore_id).toBe("raghavendra-2027");
      expect(row.location).toBe(AARADHANE_LOCATION);
      expect(row.category).toBe(AARADHANE_CATEGORY);
      expect(row.start_date).toBe("2027-08-15T00:00:00.000Z");
      expect(row.end_date).toBe("2027-08-17T00:00:00.000Z");

      // Provenance columns are dropped by default, but the drop is reported, never silent.
      expect(row.auto_generated).toBeUndefined();
      expect(unmappedFields()).toEqual(
        expect.arrayContaining(["autoGenerated", "year", "guru", "paramparaNumber"]),
      );
    });

    it("writes provenance columns only when explicitly enabled", () => {
      const row = buildSupabaseEventRow(event(), { includeProvenanceColumns: true });
      expect(row.auto_generated).toBe(true);
      expect(row.year).toBe(2027);
      expect(row.guru).toBe("raghavendra");
      expect(row.parampara_number).toBe(1);
    });

    it("refuses to build a partial row", () => {
      expect(() => buildSupabaseEventRow(event({ title: "" }))).toThrow(/has no title/);
      expect(() => buildSupabaseEventRow(event({ date: "" }))).toThrow(/has no start date/);
      expect(() => buildSupabaseEventRow(event({ endDate: "" }))).toThrow(/has no end date/);
    });
  });

  describe("ownership", () => {
    it("accepts a generator-owned event", () => {
      expect(assertOwned(event(), 2027)).toEqual({ ok: true });
    });

    it("refuses a key that does not carry the target year", () => {
      const result = assertOwned(event({ eventKey: "raghavendra-2026" }), 2027);
      expect(result.ok).toBe(false);
      expect(result).toMatchObject({ reason: expect.stringContaining("target year") });
    });

    it("refuses a key whose guru prefix is not a slug", () => {
      const result = assertOwned(event({ eventKey: "Raghavendra_Swamy-2027" }), 2027);
      expect(result.ok).toBe(false);
      expect(result).toMatchObject({ reason: expect.stringContaining("non-slug") });
    });

    it("refuses an event that is not in the Aaradhane category", () => {
      const result = assertOwned(event({ category: "Festival" as "Aaradhane" }), 2027);
      expect(result.ok).toBe(false);
      expect(result).toMatchObject({ reason: expect.stringContaining("not Aaradhane") });
    });

    it("excludes refused events from the plan instead of writing them", () => {
      const { plan, refused } = planWrite(
        [event(), event({ eventKey: "raghavendra-2026" })],
        2027,
      );
      expect(plan.keys).toEqual(["raghavendra-2027"]);
      expect(refused).toHaveLength(1);
      expect(refused[0].key).toBe("raghavendra-2026");
    });

    it("rejects a batch with duplicate keys rather than silently collapsing it", () => {
      expect(() => planWrite([event(), event()], 2027)).toThrow(/Duplicate event keys/);
    });
  });

  describe("writeAaradhaneEvents", () => {
    it("never calls the client when apply is not true", async () => {
      const { client, calls } = stubClient();
      const result = await writeAaradhaneEvents([event()], { client, year: 2027, apply: false });

      expect(calls).toEqual([]);
      expect(result.applied).toBe(false);
      expect(result.summary.planned).toBe(1);
      expect(result.created).toEqual([]);
      expect(result.updated).toEqual([]);
    });

    it("upserts on firestore_id, so a re-run updates rather than duplicates", async () => {
      const { client, calls } = stubClient({
        existing: [{ firestore_id: "raghavendra-2027", category: AARADHANE_CATEGORY }],
      });
      const result = await writeAaradhaneEvents([event()], { client, year: 2027, apply: true });

      expect(result.applied).toBe(true);
      expect(result.updated).toEqual(["raghavendra-2027"]);
      expect(result.created).toEqual([]);
      const upsert = calls.find((c) => c.op === "upsert");
      expect(upsert?.conflict).toBe("firestore_id");
    });

    it("reports a new key as created", async () => {
      const { client } = stubClient({ existing: [] });
      const result = await writeAaradhaneEvents([event()], { client, year: 2027, apply: true });
      expect(result.created).toEqual(["raghavendra-2027"]);
    });

    it("refuses to overwrite an existing row that is not generator-owned", async () => {
      const { client, calls } = stubClient({
        existing: [{ firestore_id: "raghavendra-2027", category: "Festival" }],
      });
      const result = await writeAaradhaneEvents([event()], { client, year: 2027, apply: true });

      expect(result.applied).toBe(false);
      expect(result.summary.refused).toBe(1);
      expect(result.refused[0].reason).toMatch(/not Aaradhane/);
      expect(calls.some((c) => c.op === "upsert")).toBe(false);
    });

    it("retries a failing batch and reports per-row failures without losing the rest", async () => {
      const { client, calls } = stubClient({
        upsertError: { message: "connection reset" },
        perRowError: (row) =>
          row.firestore_id === "bad-2027" ? { message: "row rejected" } : null,
      });
      const result = await writeAaradhaneEvents([event(), event({ eventKey: "bad-2027" })], {
        client,
        year: 2027,
        apply: true,
        sleep: async () => {},
      });

      expect(result.applied).toBe(true);
      expect(result.errors.map((e) => e.key)).toEqual(["bad-2027"]);
      expect(result.created).toEqual(["raghavendra-2027"]);
      // 3 batch attempts, then one per-row attempt for each of the two rows.
      expect(calls.filter((c) => c.op === "upsert")).toHaveLength(5);
    });

    it("fails loudly when nothing could be written, and names the absence of a fallback", async () => {
      const { client } = stubClient({
        upsertError: { message: "connection reset" },
        perRowError: () => ({ message: "row rejected" }),
      });
      await expect(
        writeAaradhaneEvents([event()], { client, year: 2027, apply: true, sleep: async () => {} }),
      ).rejects.toThrow(/No Firestore fallback is attempted/);
    });
  });
});
