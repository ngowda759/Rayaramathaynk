export function aaradhaneEvent(
  year: number,
  overrides: Partial<AaradhaneEvent> = {}
): AaradhaneEvent {
  return {
    eventKey: `guru-1-${year}`,
    title: "Sri Guru Aaradhane",
    description: "Aaradhane celebration",
    guru: "Sri Guru",
    category: "Aaradhane",
    date: `${year}-01-10`,
    endDate: `${year}-01-10`,
    allDay: true,
    featured: false,
    published: true,
    autoGenerated: true,
    year,
    paramparaNumber: 1,
    lunarCalendar: {
      lunarMonth: "Pauṣa",
      paksha: "Shukla",
      tithi: "Dashami",
      tithiNumber: 10,
    },
    importance: "major",
    ...overrides,
  };
}

export function raghavendraEvents(year: number): AaradhaneEvent[] {
  return ["Poorva", "Madhya", "Uttara"].map((phase, index) =>
    aaradhaneEvent(year, {
      eventKey: `raghavendra-${phase.toLowerCase()}-${year}`,
      title: `Sri Raghavendra Swamy ${phase} Aaradhane`,
      guru: "Sri Raghavendra Swamy",
      date: `${year}-05-${String(20 + index).padStart(2, "0")}`,
      endDate: `${year}-05-${String(20 + index).padStart(2, "0")}`,
      raghavendraPhase: phase as "Poorva" | "Madhya" | "Uttara",
      paramparaNumber: 17,
    })
  );
}

export function aaradhaneDataset(
  year: number,
  events: AaradhaneEvent[]
): AaradhaneYearDataset {
  return buildAaradhaneYearDataset(
    year,
    events,
    `Data_flows/Panchanga/years/${year}.json`,
    `${year}-01-01T00:00:00+05:30`
  );
}

/**
 * In-memory `ObjectStorage` used by the publisher tests.
 *
 * `putFailures` simulates an upload that never lands; `corruptReads` simulates a
 * verification read that returns different content after a successful upload.
 */
export class MemoryStorage implements ObjectStorage {
  readonly bucket = "test-bucket";
  readonly objects = new Map<string, string>();
  readonly writes: string[] = [];
  readonly putFailures = new Set<string>();
  readonly readFailures = new Set<string>();
  readonly corruptReads = new Map<string, string>();

  seed(path: string, value: unknown): void {
    this.objects.set(path, `${JSON.stringify(value, null, 2)}\n`);
  }

  async getText(path: string): Promise<StorageGetResult> {
    if (this.readFailures.has(path)) {
      return { ok: false, text: null, status: 500, error: "forced read failure" };
    }
    if (this.corruptReads.has(path)) {
      return { ok: true, text: this.corruptReads.get(path)!, status: 200 };
    }
    const text = this.objects.get(path);
    if (text === undefined) {
      return { ok: false, text: null, status: 404, error: "not found" };
    }
    return { ok: true, text, status: 200 };
  }

  async putText(path: string, text: string): Promise<StoragePutResult> {
    this.writes.push(path);
    if (this.putFailures.has(path)) {
      return { ok: false, status: 500, error: "forced upload failure" };
    }
    this.objects.set(path, text);
    return { ok: true, status: 200 };
  }

  async list(prefix: string): Promise<StorageListResult> {
    const entries: StorageListEntry[] = [...this.objects.keys()]
      .filter((key) => key.startsWith(prefix))
      .map((key) => ({ name: key.slice(prefix.length), id: null }));
    return { ok: true, entries, status: 200 };
  }
}
