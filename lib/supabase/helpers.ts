/**
 * Returns a public URL for a given bucket and path using Supabase Storage.
 * Assumes the bucket is public.
 */
export function getPublicUrl(bucket: string, path: string): string {
  const baseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL?.replace(/\/$/, '');
  if (!baseUrl) {
    console.error('[supabase] Missing NEXT_PUBLIC_SUPABASE_URL env var');
    return '';
  }
  // Encode path but preserve slashes
  const encodedPath = encodeURIComponent(path).replace(/%2F/g, '/');
  return `${baseUrl}/storage/v1/object/public/${bucket}/${encodedPath}`;
}

/**
 * Normalises a hero image value.
 * - Handles Supabase dashboard URLs, extracting the storage path.
 * - Handles public URLs generated by getPublicUrl, extracting the relative path.
 * - Handles legacy dashboard URLs without preview param.
 * - Returns raw relative path otherwise.
 */
export function normaliseHeroImage(value: string): string {
  if (!value) return '';

  // Supabase dashboard URL with preview param
  // Example: https://supabase.com/dashboard/project/<proj>/storage/files/buckets/<bucket>?path=Folder+Name&preview=filename.jpg
  const dashMatch = value.match(/buckets\/[^/]+\?path=([^&]+)&preview=([^&]+)/i);
  if (dashMatch) {
    const folder = decodeURIComponent(dashMatch[1].replace(/\+/g, ' '));
    const file = decodeURIComponent(dashMatch[2]);
    return `${folder}/${file}`;
  }

  // Public URL pattern from Supabase getPublicUrl
  const publicMatch = value.match(/https?:\/\/[^\/]+\/storage\/v1\/object\/public\/[^\/]+\/(.+)$/i);
  if (publicMatch) {
    return decodeURIComponent(publicMatch[1]);
  }

  // Legacy dashboard URL without preview (bucket path after /buckets/)
  const legacyMatch = value.match(/buckets\/[^/]+\/(.+)$/i);
  if (legacyMatch) {
    return decodeURIComponent(legacyMatch[1]);
  }

  // Assume already a relative path like "General Pictures/hero.jpg"
  return value;
}
