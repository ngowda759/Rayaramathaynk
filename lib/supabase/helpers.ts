/**
 * Returns a public URL for a given bucket and path using Supabase Storage.
 * Assumes the bucket is public.
 */
export function getPublicUrl(bucket: string, path: string): string {
  // Manually construct the public URL without using the Supabase Storage SDK.
  const base = process.env.NEXT_PUBLIC_SUPABASE_URL?.replace(/^https:\/\//, '');
  if (!base) {
    console.warn('Missing NEXT_PUBLIC_SUPABASE_URL env var for public URL construction');
    return '';
  }
  // Encode each path segment separately to avoid double‑encoding.
  const encodedPath = path.split('/').map(encodeURIComponent).join('/')
  return `https://${base}/storage/v1/object/public/${bucket}/${encodedPath}`;
}

/**
 * Normalises a hero image value.
 * - Handles Supabase dashboard URLs, extracting the storage path.
 * - Handles public URLs generated by getPublicUrl, extracting the relative path.
 * - Handles legacy dashboard URLs without preview param.
 * - Returns raw relative path otherwise.
 */
export function normaliseHeroImage(value: string): string {
  // Return empty string for falsy input
  if (!value) return '';

  // Helper to decode plus‑sign spaces and percent‑encoding
  const decode = (s: string) => decodeURIComponent(s.replace(/\\+/g, ' '));

  // Attempt to treat the value as a URL first (Supabase dashboard or public URL)
  try {
    const url = new URL(value);

    // Public storage URL (e.g. https://<project>.supabase.co/storage/v1/object/public/<bucket>/<path>)
    if (url.pathname.includes('/object/public/')) {
      // Split after '/object/public/' to get "<bucket>/<path>"
      const [, bucketAndPath] = url.pathname.split('/object/public/');
      if (bucketAndPath) {
        const slashIdx = bucketAndPath.indexOf('/');
        if (slashIdx !== -1) {
          const path = bucketAndPath.slice(slashIdx + 1);
          return decode(path);
        }
      }
    }

    // Supabase Dashboard URL – contains '/buckets/' and query parameters
    const hostname = url.hostname.toLowerCase();
    const isSupabaseHost = hostname === 'supabase.com' || hostname.endsWith('.supabase.com');
    if (isSupabaseHost && url.pathname.includes('/buckets/')) {
      const pathParam = url.searchParams.get('path');
      const preview = url.searchParams.get('preview');
      if (pathParam) {
        const folder = decode(pathParam);
        if (preview) {
          const file = decode(preview);
          return `${folder}/${file}`;
        }
        return folder;
      }
    }
  } catch {
    // Not a valid URL – fall back to string handling
  }

  // Legacy dashboard string format: "buckets/<bucket>/<relativePath>"
  const legacyPrefix = 'buckets/';
  if (value.startsWith(legacyPrefix)) {
    const parts = value.split('/');
    // Expected: ['buckets', '<bucket>', '<path>', ...]
    if (parts.length >= 3) {
      const relative = parts.slice(2).join('/');
      return decode(relative);
    }
  }

  // Assume the value is already a relative path – just decode plus signs
  return decode(value);
}
