/**
 * Batch update events for efficiency
 * Use this when updating many events at once
 */
export async function batchUpdateFirestoreEvents(
  generatedEvents: GeneratedAaradhaneEvent[],
  year: number,
  updateExisting: boolean = true
): Promise<UpdateResult> {
  if (!db) {
    throw new Error("Firebase not configured");
  }
  
  const result: UpdateResult = {
    created: [],
    updated: [],
    skipped: [],
    errors: [],
    summary: {
      created: 0,
      updated: 0,
      skipped: 0,
      errors: 0,
    },
  };
  
  // Get existing events
  let existingEvents: Map<string, ExistingEvent> = new Map();
  
  if (updateExisting) {
    const existing = await getExistingAutoGeneratedEvents(year);
    existingEvents = new Map(existing.map((e) => [e.id, e]));
  }
  
  // Use batch write for efficiency
  const batch = writeBatch(db);
  let batchCount = 0;
  const BATCH_SIZE = 500; // Firestore limit
  
  for (const event of generatedEvents) {
    try {
      // Find existing event
      let existingId: string | null = null;
      
      if (updateExisting) {
        for (const [id, existing] of existingEvents) {
          if (
            existing.guru === event.guru &&
            existing.year === event.year &&
            existing.autoGenerated
          ) {
            if (
              event.guru === "Sri Raghavendra Swamy" &&
              event.raghavendraPhase
            ) {
              const existingPhase = (existing as unknown as Record<string, unknown>).raghavendraPhase;
              if (existingPhase !== event.raghavendraPhase) {
                continue;
              }
            }
            existingId = id;
            break;
          }
        }
      }
      
      const firestoreDoc = eventToFirestoreDocument(event);
      const now = Timestamp.now();
      
      if (existingId) {
        // Update in batch
        const docRef = doc(db, COLLECTION_NAME, existingId);
        batch.update(docRef, {
          ...firestoreDoc,
          updatedAt: now,
        });
        
        result.updated.push({
          event,
          action: "updated",
          existingId,
        });
        result.summary.updated++;
      } else {
        // Create in batch
        const docRef = doc(collection(db, COLLECTION_NAME));
        batch.set(docRef, {
          ...firestoreDoc,
          createdAt: now,
          updatedAt: now,
        });
        
        result.created.push({
          event,
          action: "created",
          existingId: docRef.id,
        });
        result.summary.created++;
      }
      
      batchCount++;
      
      // Commit batch if it reaches the limit
      if (batchCount >= BATCH_SIZE) {
        await batch.commit();
        batchCount = 0;
      }
    } catch (error) {
      result.errors.push({
        event,
        action: "error",
        error: error instanceof Error ? error.message : String(error),
      });
      result.summary.errors++;
    }
  }
  
  // Commit remaining batch
  if (batchCount > 0) {
    await batch.commit();
  }
  
  return result;
}
