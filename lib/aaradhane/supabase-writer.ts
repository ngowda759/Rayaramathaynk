/**
 * Supabase persistence for generated Aaradhane events.
 *
 * This is the sole write destination for the Aaradhane generator. It deliberately
 * has no Firestore import: there is no fallback path, so a Supabase outage can
 * never silently divert a write to another database.
 *
 * Design constraints (see docs/PR-D4a_AARADHANE_WRITER.md):
 *   - Identity is the canonical key `${guru.id}-${year}` (the generator's
 *     `eventKey`). No invented prefix, no phase suffix.
 *   - Writes are idempotent upserts on `firestore_id`; the uniqueness constraint
 *     on that column is what makes a re-run a no-op.
 *   - Rows the generator does not own are never overwritten.
 *   - Rows are never deleted. A shrinking expected set is reported, not applied.
 *   - Writing requires an explicit `apply`; otherwise the plan is returned and the
 *     client is never called.
 *
 * The client is injected so the write path is testable without a database: tests
 * pass a stub and assert on the recorded calls.
 */
import type { SupabaseClient } from "@supabase/supabase-js";

import { GeneratedAaradhaneEvent } from "@/types/aaradhane-generator";

export const EVENTS_TABLE = "events";

/** The location every generated Aaradhane is held at. */
export const AARADHANE_LOCATION = "Sri Raghavendra Swamy Matha, Yelahanka, Bangalore";

/** The category that marks a row as generator-owned. */
export const AARADHANE_CATEGORY = "Aaradhane";

