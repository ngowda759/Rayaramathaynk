/** A row destined for the `events` table. */
export interface AaradhaneEventRow {
  firestore_id: string;
  title: string;
  description: string;
  location: string;
  start_date: string;
  end_date: string;
  start_time: string | null;
  end_time: string | null;
  featured: boolean;
  published: boolean;
  category: string;
  image_url: string | null;
  status: "Upcoming" | "Ongoing" | "Completed";
  [key: string]: unknown;
}

/**
 * Derive the display status from the event's civil dates.
 *
 * Compared at day granularity in UTC so the result does not depend on the host
 * time zone; the dates are already Indian civil dates.
 */
export function determineEventStatus(
  startDate: string,
  endDate: string,
  now: Date = new Date()
): "Upcoming" | "Ongoing" | "Completed" {
  const start = Date.parse(`${startDate}T00:00:00Z`);
  const end = Date.parse(`${endDate}T23:59:59Z`);
  const today = Date.parse(`${now.toISOString().slice(0, 10)}T00:00:00Z`);

  if (Number.isNaN(start) || Number.isNaN(end)) {
    throw new Error(`Invalid event dates: start=${startDate} end=${endDate}`);
  }
  if (end < today) return "Completed";
  if (start <= today) return "Ongoing";
  return "Upcoming";
}

/**
 * The canonical identity of a generated event.
 *
 * This is the generator's `eventKey` unchanged. It is asserted, never rebuilt,
 * so the writer cannot drift from the value the generator already deduplicates on.
 */
export function canonicalEventId(event: Pick<GeneratedAaradhaneEvent, "eventKey">): string {
  const key = String(event.eventKey ?? "").trim();
  if (!key) throw new Error("Generated event has no eventKey");
  return key;
}

/**
 * Build the destination row for one generated event.
 *
 * Throws rather than writing a partially-mapped row: a missing title or date is a
 * generator bug, and a NOT NULL violation surfacing later is harder to diagnose.
 */
export function buildSupabaseEventRow(
  event: GeneratedAaradhaneEvent,
  options: { includeProvenanceColumns?: boolean; now?: Date } = {}
): AaradhaneEventRow {
  const firestore_id = canonicalEventId(event);

  if (!event.title?.trim()) throw new Error(`Event ${firestore_id} has no title`);
  if (!event.date) throw new Error(`Event ${firestore_id} has no start date`);
  if (!event.endDate) throw new Error(`Event ${firestore_id} has no end date`);

  const row: AaradhaneEventRow = {
    firestore_id,
    title: event.title,
    description: event.description ?? "",
    location: AARADHANE_LOCATION,
    start_date: `${event.date}T00:00:00.000Z`,
    end_date: `${event.endDate}T00:00:00.000Z`,
    start_time: null,
    end_time: null,
    featured: Boolean(event.featured),
    published: Boolean(event.published),
    category: AARADHANE_CATEGORY,
    image_url: null,
    status: determineEventStatus(event.date, event.endDate, options.now),
  };

  if (options.includeProvenanceColumns) {
    row.auto_generated = event.autoGenerated;
    row.year = event.year;
    row.guru = event.guru;
    row.parampara_number = event.paramparaNumber;
    row.raghavendra_phase = event.raghavendraPhase ?? null;
    row.lunar_calendar = event.lunarCalendar;
    row.rituals = event.rituals ?? [];
    row.offerings = event.offerings ?? [];
    row.significance = event.significance ?? event.description ?? "";
  }

  return row;
}

/** Generated fields this writer does not persist, for diagnostics. */
export function unmappedFields(): string[] {
  return FIELD_MAPPING.filter((m) => m.column === null).map((m) => String(m.source));
}

export interface WritePlan {
  rows: AaradhaneEventRow[];
  /** Keys that will be created or updated. */
  keys: string[];
  /** Fields present in the input but absent from the destination. */
  unmapped: string[];
}

export interface WriteResult {
  applied: boolean;
  planned: number;
  created: string[];
  updated: string[];
  refused: Array<{ key: string; reason: string }>;
  errors: Array<{ key: string; message: string }>;
  summary: { planned: number; created: number; updated: number; refused: number; errors: number };
}

export interface WriteOptions {
  client: SupabaseClient;
  year: number;
  /** Writing requires an explicit true. Anything else is a plan-only run. */
  apply: boolean;
  includeProvenanceColumns?: boolean;
  maxAttempts?: number;
  now?: Date;
  /** Injected in tests to avoid real backoff sleeps. */
  sleep?: (ms: number) => Promise<void>;
}

const defaultSleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms));

/**
 * Refuse any event that is not generator-owned.
 *
 * Ownership is the canonical key plus the Aaradhane category. A row whose key is
 * not `${slug}-${year}` for the target year, or whose category is not Aaradhane,
 * is rejected rather than written — this is what stops the generator from
 * clobbering a hand-curated event that happens to share an id.
 */
export function assertOwned(
  event: GeneratedAaradhaneEvent,
  year: number
): { ok: true } | { ok: false; reason: string } {
  const key = canonicalEventId(event);
  if (!key.endsWith(`-${year}`)) {
    return { ok: false, reason: `key "${key}" does not end with the target year ${year}` };
  }
  const slug = key.slice(0, -(String(year).length + 1));
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
    return { ok: false, reason: `key "${key}" has a non-slug guru prefix` };
  }
  if (event.category !== AARADHANE_CATEGORY) {
    return { ok: false, reason: `category "${event.category}" is not ${AARADHANE_CATEGORY}` };
  }
  return { ok: true };
}

/**
 * Build the write plan without touching the database.
 *
 * Split out so the plan can be asserted in tests and printed in a dry run.
 */
export function planWrite(
  events: GeneratedAaradhaneEvent[],
  year: number,
  options: { includeProvenanceColumns?: boolean; now?: Date } = {}
): { plan: WritePlan; refused: Array<{ key: string; reason: string }> } {
  const refused: Array<{ key: string; reason: string }> = [];
  const rows: AaradhaneEventRow[] = [];

  for (const event of events) {
    const owned = assertOwned(event, year);
    if (!owned.ok) {
      refused.push({ key: canonicalEventId(event), reason: owned.reason });
      continue;
    }
    rows.push(buildSupabaseEventRow(event, options));
  }

  const keys = rows.map((r) => r.firestore_id);
  const duplicates = keys.filter((k, i) => keys.indexOf(k) !== i);
  if (duplicates.length > 0) {
    throw new Error(
      `Duplicate event keys in one batch: ${[...new Set(duplicates)].join(", ")}. ` +
        "The generator must emit one event per key."
    );
  }

  return { plan: { rows, keys, unmapped: unmappedFields() }, refused };
}

/** Narrow a Supabase row to the columns this writer manages. */
async function existingOwnership(
  client: SupabaseClient,
  keys: string[]
): Promise<Map<string, string>> {
  const owned = new Map<string, string>();
  if (keys.length === 0) return owned;

  const { data, error } = await client
    .from(EVENTS_TABLE)
    .select("firestore_id, category")
    .in("firestore_id", keys);

  if (error) {
    throw new Error(`Could not read existing ownership: ${error.message}`);
  }
  for (const row of (data ?? []) as Array<{ firestore_id: string; category: string | null }>) {
    owned.set(row.firestore_id, row.category ?? "");
  }
  return owned;
}

/**
 * Persist generated events to Supabase.
 *
 * Returns a result describing what was planned, written, refused and failed. A
 * plan-only run (`apply !== true`) never calls the client.
 */
export async function writeAaradhaneEvents(
  events: GeneratedAaradhaneEvent[],
  options: WriteOptions
): Promise<WriteResult> {
  const {
    client,
    year,
    apply,
    includeProvenanceColumns = false,
    maxAttempts = 3,
    now,
    sleep = defaultSleep,
  } = options;

  const { plan, refused } = planWrite(events, year, { includeProvenanceColumns, now });

  const result: WriteResult = {
    applied: false,
    planned: plan.rows.length,
    created: [],
    updated: [],
    refused,
    errors: [],
    summary: { planned: plan.rows.length, created: 0, updated: 0, refused: refused.length, errors: 0 },
  };

  if (!apply) {
    return result;
  }

  const ownership = await existingOwnership(client, plan.keys);
  const writable = plan.rows.filter((row) => {
    const existingCategory = ownership.get(row.firestore_id);
    if (existingCategory !== undefined && existingCategory !== AARADHANE_CATEGORY) {
      refused.push({
        key: row.firestore_id,
        reason: `existing row has category "${existingCategory}", not ${AARADHANE_CATEGORY}`,
      });
      result.summary.refused = refused.length;
      return false;
    }
    if (existingCategory === undefined) result.created.push(row.firestore_id);
    else result.updated.push(row.firestore_id);
    return true;
  });

  if (writable.length === 0) {
    result.summary.planned = plan.rows.length;
    return result;
  }

  let lastError: Error | null = null;
  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    const { error } = await client
      .from(EVENTS_TABLE)
      .upsert(writable, { onConflict: "firestore_id" });

    if (!error) {
      result.applied = true;
      result.summary.created = result.created.length;
      result.summary.updated = result.updated.length;
      return result;
    }

    lastError = new Error(error.message);
    if (attempt < maxAttempts) await sleep(attempt * 250);
  }

  // Batch failed: retry row by row so one bad row cannot lose the year, exactly as
  // the migration runner does.
  const perRowApplied: string[] = [];
  for (const row of writable) {
    const { error } = await client
      .from(EVENTS_TABLE)
      .upsert([row], { onConflict: "firestore_id" });
    if (error) {
      result.errors.push({ key: row.firestore_id, message: error.message });
    } else {
      perRowApplied.push(row.firestore_id);
    }
  }

  if (perRowApplied.length === 0) {
    throw new Error(
      `Supabase upsert failed after ${maxAttempts} attempts: ${lastError?.message ?? "unknown error"}. ` +
        "No Firestore fallback is attempted."
    );
  }

  result.applied = true;
  result.created = result.created.filter((k) => perRowApplied.includes(k));
  result.updated = result.updated.filter((k) => perRowApplied.includes(k));
  result.summary.created = result.created.length;
  result.summary.updated = result.updated.length;
  result.summary.errors = result.errors.length;

  return result;
}

/** Human-readable summary for the generator's console output. */
export function printWriteSummary(result: WriteResult): void {
  const line = "=".repeat(60);
  console.log(`\n${line}\nSUPABASE WRITE SUMMARY\n${line}`);
  console.log(`  Planned: ${result.summary.planned}`);
  console.log(`  Created: ${result.summary.created}`);
  console.log(`  Updated: ${result.summary.updated}`);
  console.log(`  Refused: ${result.summary.refused}`);
  console.log(`  Errors:  ${result.summary.errors}`);
  if (!result.applied) {
    console.log("\n  (plan only — no rows were written)");
  }
  for (const r of result.refused) console.log(`  ⊘ ${r.key}: ${r.reason}`);
  for (const e of result.errors) console.log(`  ✗ ${e.key}: ${e.message}`);
}
